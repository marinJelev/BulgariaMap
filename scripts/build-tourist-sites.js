function build() {
  const seenAtLocation = {};
  const sites = RAW_SITES.map((entry, i) => {
    const [number, name, locationKey, url] = entry;
    const base = LOCATIONS[locationKey];
    if (!base) throw new Error(`Unknown location key "${locationKey}" for site ${number} ${name}`);

    const count = seenAtLocation[locationKey] || 0;
    seenAtLocation[locationKey] = count + 1;
    const [lat, lon] = jitter(base[0], base[1], count);

    return {
      id: `${number}-${i}`,
      number,
      group: groupNumber(number),
      name,
      location: locationKey,
      locationLabel: LOCATION_LABELS[locationKey] || locationKey,
      lat: Number(lat.toFixed(5)),
      lon: Number(lon.toFixed(5)),
      url
    };
  });

  const groups = new Set(sites.map(s => s.group));

  const geojson = {
    type: 'FeatureCollection',
    features: sites.map(s => ({
      type: 'Feature',
      id: s.id,
      properties: {
        id: s.id,
        number: s.number,
        group: s.group,
        name: s.name,
        location: s.locationLabel,
        url: s.url
      },
      geometry: { type: 'Point', coordinates: [s.lon, s.lat] }
    }))
  };

  const outPath = path.join(__dirname, '..', 'public', 'data', 'tourist-sites.json');
  fs.writeFileSync(outPath, JSON.stringify(geojson));
  console.log(`Wrote ${sites.length} site entries across ${groups.size} official points to ${outPath}`);
}

build();
