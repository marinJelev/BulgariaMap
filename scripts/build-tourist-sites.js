function groupNumber(officialNumber) {
  const match = officialNumber.match(/^\d+/);
  return match ? match[0] : officialNumber;
}

// Spread out pins that share identical coordinates (same town/landmark) so
// they don't stack exactly on top of each other on the map.
function jitter(lat, lon, index) {
  if (index === 0) return [lat, lon];
  const angle = (index * 137.508) * (Math.PI / 180); // golden-angle spiral
  const radius = 0.0022 * Math.sqrt(index);
  return [lat + radius * Math.sin(angle), lon + radius * Math.cos(angle)];
}

